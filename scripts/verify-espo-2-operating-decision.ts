  assert(second.fingerprint === first.fingerprint, "deterministic rebuild");
  assert(
    operatingDecisionFingerprint(second) === first.fingerprint,
    "helper",
  );
  assert(getOperatingDecision().fingerprint === first.fingerprint, "cache");
  const mutated = getOperatingDecision();
  (mutated as { actCount: number }).actCount = -1;
  assert(getOperatingDecision().actCount === first.actCount, "clone-on-get");
  clearOperatingDecision();
  const third = buildOperatingDecision();
  assert(third.fingerprint === first.fingerprint, "after clear");
  console.log("PASS Deterministic");

