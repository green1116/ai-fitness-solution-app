      if (!rec) return false;
      const mapped = operatingDecisionFromQueue(rec.status);
      return (
        r.id === rec.id.replace(/^espo-1:/, "espo-2:") &&
        r.itemId === rec.id &&
        r.customerId === rec.customerId &&
        r.decision === mapped.decision &&
        r.priority === rec.priority &&
        r.reason === mapped.reason &&
        r.fingerprint.length === 64 &&
        r.ordinal === rec.ordinal
      );
